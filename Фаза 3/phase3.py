def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def moves(desc):
    kinds = [p.strip()[0] for p in desc.split(";")]
    return {k: kinds.count(k) for k in "EXRW"}


def uc_class(n):
    return ("простой", 5) if n <= 3 else ("средний", 10) if n <= 7 else ("сложный", 15)


