    md += ["**Use cases (UUCW).** Простой (до 3 транзакций) — 5, средний (4–7) — 10, сложный (больше 7) — 15.", ""]
    uucw = sum(uc_class(n)[1] for n in TRANSACTIONS.values())
    md += [table(["UC", "Use case", "Транзакций", "Класс", "Вес"],
                 [[k, UC[k][0], n, *uc_class(n)] for k, n in TRANSACTIONS.items()] + [["", "**UUCW**", "", "", f"**{uucw}**"]]), ""]
    tf = sum(w * r for _, _, w, r in TCF)
    ef = sum(w * r for _, _, w, r in ECF)
    tcf, ecf = 0.6 + 0.01 * tf, 1.4 - 0.03 * ef
    md += ["**Технические факторы (TCF)**, оценка 0–5", ""]
    md += [table(["Код", "Фактор", "Вес", "Оценка", "Вес × оценка"],
                 [[c, n, w, r, f"{w * r:g}"] for c, n, w, r in TCF] + [["", "**TFactor**", "", "", f"**{tf:g}**"]]), ""]
    md += [f"$TCF = 0{{,}}6 + 0{{,}}01 \\cdot {tf:g} = {tcf:.2f}$", ""]
    md += ["**Факторы среды (ECF)**, оценка 0–5", ""]
    md += [table(["Код", "Фактор", "Вес", "Оценка", "Вес × оценка"],
                 [[c, n, w, r, f"{w * r:g}"] for c, n, w, r in ECF] + [["", "**EFactor**", "", "", f"**{ef:g}**"]]), ""]
    md += [f"$ECF = 1{{,}}4 - 0{{,}}03 \\cdot {ef:g} = {ecf:.2f}$", ""]
    ucp = (uaw + uucw) * tcf * ecf
    low = sum(1 for c, _, _, r in ECF[:6] if r < 3) + sum(1 for c, _, _, r in ECF[6:] if r > 3)
    rate = 20 if low <= 2 else 28
    md += [f"$UCP = (UAW + UUCW) \\cdot TCF \\cdot ECF = ({uaw} + {uucw}) \\cdot {tcf:.2f} \\cdot {ecf:.2f} = {ucp:.1f}$", ""]
    md += [f"**Трудозатраты.** По правилу Шнайдера — Уинтерса считаем факторы E1–E6 с оценкой ниже 3 и E7–E8 с оценкой выше 3: "
           f"получается {low}, это не больше 2, поэтому берём {rate} чел.-ч на UCP (норматив Карнера). "
           f"Итог: {ucp:.1f} × {rate} = **{ucp * rate:.0f} чел.-ч**. Для нижней границы используем 15 чел.-ч на UCP: "
           f"{ucp * 15:.0f} чел.-ч.", ""]

    # ---- экспертная оценка
    md += ["## 4. Коллективная экспертная оценка", ""]
    md += ["Метод — покер планирования. Оцениваются use cases (реализация серверной и клиентской части с модульными тестами) "
           "и отдельно сквозные работы, не привязанные к одному use case. Единица — человеко-часы, карты 5, 8, 13, 20, 40, 60, 100. "
           "Раунд 1 — оценки вскрываются одновременно. Если крайние оценки расходятся, их авторы объясняют свою позицию, "
           "затем раунд 2 до единой оценки.", ""]
    items = [(k, UC[k][0], *POKER_UC[k]) for k in POKER_UC] + [(k, *v) for k, v in POKER_X.items()]
    rows, s_final, s_pert, var = [], 0, 0.0, 0.0
    for code, name, r1, fin in items:
        o, p = min(r1), max(r1)
        e = (o + 4 * fin + p) / 6
        sd = (p - o) / 6
        s_final += fin
        s_pert += e
        var += sd ** 2
        rows.append([code, name, *r1, "да" if p > o else "нет", f"**{fin}**", f"{e:.1f}", f"{sd:.1f}"])
    sum_uc = sum(v[1] for v in POKER_UC.values())
    sum_x = sum(v[2] for v in POKER_X.values())
    rows.append(["", "**Сумма**", "", "", "", "", f"**{s_final}**", f"**{s_pert:.0f}**", f"{sqrt(var):.1f}"])
    md += [table(["Код", "Элемент"] + SHORT + ["Обсуждение", "Итог, ч", "PERT, ч", "σ"], rows), ""]
    md += ["Что обсуждали при самых больших расхождениях:", "",
           "- **UC8 (40 / 60 / 100).** Высокая оценка — из-за работы с камерой в разных мобильных браузерах и ручного режима; "
           "низкая предполагала готовую библиотеку распознавания QR. Сошлись на 60: библиотека есть, но нужны ручной поиск и обработка отказа в доступе к камере.",
           "- **UC3 (20 / 40 / 40).** Низкая оценка не учитывала одновременную запись на последнее место и лист ожидания. Приняли 40.",
           "- **UC13 (20 / 40 / 40).** Агрегирующие запросы и графики; приняли 40.",
           "- **X3 (60 / 100 / 60).** Спор о глубине тестирования на мобильных устройствах; приняли промежуточные 80.", ""]
    total_exp = s_final * (1 + MGMT)
    total_pert = s_pert * (1 + MGMT)
    sd_tot = sqrt(var) * (1 + MGMT)
    md += ["**Агрегация в оценку проекта**", "",
           f"- Use cases: {sum_uc} чел.-ч; сквозные работы: {sum_x} чел.-ч; вместе {s_final} чел.-ч.",
           f"- Управление и коммуникации: +{MGMT:.0%} → **{total_exp:.0f} чел.-ч** (сумма согласованных оценок).",
           "- Трёхточечная проверка: по каждому элементу минимум и максимум первого раунда берутся как оптимистичная и "
           "пессимистичная оценки, согласованная — как наиболее вероятная; $E = (O + 4M + P)/6$, $\\sigma = (P - O)/6$. "
           f"Сумма с учётом управления — {total_pert:.0f} чел.-ч, $\\sigma$ = {sd_tot:.0f} чел.-ч, "
           f"то есть примерно {total_pert - 2 * sd_tot:.0f}–{total_pert + 2 * sd_tot:.0f} чел.-ч (±2σ). "
           "Оценка PERT почти совпала с суммой согласованных оценок. Интервал узкий, потому что отражает только "
           "разброс мнений трёх экспертов и считает ошибки по элементам независимыми; риски самого проекта "
           "(смена требований, незнакомые технологии) в него не входят.", ""]

    # ---- сравнение
    md += ["## 5. Сравнение оценок и выводы", ""]
    cosmic_lo, cosmic_hi = cfp * PDR_RANGE[0], cfp * PDR_RANGE[1]
    md += [table(["Метод", "Размер", "Трудозатраты, чел.-ч", "Комментарий"], [
        ["COSMIC", f"{cfp} CFP", f"{cosmic_lo}–{cosmic_hi}",
         f"производительность {PDR_RANGE[0]}–{PDR_RANGE[1]} ч/CFP — наше допущение, своей статистики нет"],
        ["Use Case Points", f"{ucp:.1f} UCP", f"{ucp * 15:.0f}–{ucp * rate:.0f}", f"15–{rate} чел.-ч на UCP"],
        ["Экспертная (покер)", f"{len(items)} элементов", f"{total_exp:.0f} (PERT: {total_pert:.0f} ± {2 * sd_tot:.0f})",
         "снизу вверх, с управлением 15 %"]]), ""]
    fte = sum(t[1] for t in TEAM)
    cap = fte * HOURS_MONTH
    md += [f"- **Соотношение размеров.** На 1 CFP по экспертной оценке приходится {total_exp / cfp:.1f} чел.-ч, "
           f"на 1 UCP — {total_exp / ucp:.1f} чел.-ч. Первое попадает в принятый диапазон, второе заметно ниже норматива Карнера.",
           f"- **Почему UCP выше остальных в {ucp * rate / total_exp:.1f} раза.** Норматив 20 чел.-ч на UCP получен на проектах 1990-х годов "
           "и включает полный цикл с документацией. Мы оценивали MVP на готовых фреймворках. Кроме того, UCP грубо "
           f"округляет сложность: 7 «простых» use cases получают по 5 баллов, хотя по покеру они различаются втрое (13–40 ч).",
           f"- **Масштаб.** Небольшой проект: рабочая оценка — **{total_exp:.0f}–{ucp * 15:.0f} чел.-ч** "
           f"({total_exp / HOURS_MONTH:.1f}–{ucp * 15 / HOURS_MONTH:.1f} чел.-мес.), верхняя граница на случай полного цикла — "
           f"{ucp * rate:.0f} чел.-ч ({ucp * rate / HOURS_MONTH:.1f} чел.-мес.).", ""]
    md += ["**Команда**", ""]
    md += [table(["Роль", "Занятость, ставок", "Особые требования"], [[r, f"{f:g}", n] for r, f, n in TEAM]
                 + [["**Всего**", f"**{fte:g}**", f"{cap:.0f} чел.-ч в месяц"]]), ""]
    md += [f"**Срок.** При {fte:g} ставках: {total_exp:.0f} / {cap:.0f} = {total_exp / cap:.1f} мес. по экспертной оценке, "
           f"{ucp * 15 / cap:.1f} мес. по нижней границе UCP, {ucp * rate / cap:.1f} мес. по верхней. "
           f"Ориентир для плана — **около {round(ucp * 15 / cap * 2) / 2:g} месяцев**; экспертная оценка без резерва "
           "для обещаний заказчику слишком оптимистична. Увеличивать команду сверх 4–5 человек нет смысла: работа плохо "
           "распараллеливается на 13 связанных use cases.", ""]
    drop = [("UC13", "Статистика посещаемости", "данные можно получить из экспорта CSV"),
            ("UC11", "Обратная связь", "заменяется внешней формой опроса"),
            ("UC12", "Модерация", "в MVP администратор подтверждает организаторов вручную, без отдельного интерфейса"),
            ("UC10", "Уведомления и напоминания", "остаются только письма о записи и отмене из UC3, UC4, UC7")]
    saved_h = sum(POKER_UC[k][1] for k, _, _ in drop)
    saved_cfp = sum(per_uc[k] for k, _, _ in drop)
    md += ["**Что можно отбросить при нехватке ресурсов**", ""]
    md += [table(["UC", "Фича", "Покер, ч", "CFP", "Чем заменить"],
                 [[k, n, POKER_UC[k][1], per_uc[k], why] for k, n, why in drop]
                 + [["", "**Итого**", f"**{saved_h}**", f"**{saved_cfp}**", ""]]), ""]
    md += [f"Эти четыре фичи не входят в основной путь «создать мероприятие → записаться → пройти по QR», но дают "
           f"{saved_h} из {sum_uc} чел.-ч по use cases ({saved_h / sum_uc:.0%}) и {saved_cfp} из {cfp} CFP ({saved_cfp / cfp:.0%}). "
           "Ещё один кандидат — лист ожидания внутри UC3, UC4 и UC7: отдельным use case он не является, "
           "но усложняет три сценария сразу.", ""]

    Path(__file__).with_name("README.md").write_text("\n".join(md), encoding="utf-8")
    print(f"CFP={cfp} {tot} по UC: {per_uc}")
    print(f"UAW={uaw} UUCW={uucw} TF={tf} EF={ef} TCF={tcf:.2f} ECF={ecf:.2f} UCP={ucp:.1f} rate={rate} -> {ucp * 15:.0f}..{ucp * rate:.0f}")
    print(f"Покер: UC={sum_uc} X={sum_x} всего={s_final} с упр.={total_exp:.0f}; PERT={total_pert:.0f} sd={sd_tot:.0f}")
    print(f"COSMIC {cosmic_lo}-{cosmic_hi}; ч/CFP={total_exp / cfp:.1f}; ч/UCP={total_exp / ucp:.1f}")
    print(f"FTE={fte} cap={cap}; срок {total_exp / cap:.1f}/{ucp * 15 / cap:.1f}/{ucp * rate / cap:.1f}; drop {saved_h} ч {saved_cfp} CFP")


